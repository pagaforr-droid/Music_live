function formatSampleDisplayLabel(folder: DrumKit1400Folder, fileName: string, featured: boolean): string {
  const base = fileName.replace(/\.[^.]+$/, '');
  const prefixStar = featured ? '★ ' : '';
  if (/natural/i.test(base)) {
    return `${prefixStar}${base.replace(/_/g, ' ')} (Natural Studio)`;
  }
  if (folder === 'Claps') {
    return `${prefixStar}${base} (Clap)`;
  }
  return `${prefixStar}${base}`;
}

function buildCatalogFromManifest(
  manifest: Record<DrumKit1400Folder, readonly string[]>
): DrumKit1400SampleEntry[] {
  const entries: DrumKit1400SampleEntry[] = [];
  const folderMeta: Record<
    DrumKit1400Folder,
    { category: CustomSampleCategory; subKind: DrumKit1400SampleEntry['subKind'] }
  > = {
    Kicks: { category: 'kick', subKind: 'kick' },
    Snares: { category: 'snare', subKind: 'snare' },
    Hats: { category: 'hat', subKind: 'hat' },
    Claps: { category: 'snare', subKind: 'clap' },
  };

  (Object.keys(manifest) as DrumKit1400Folder[]).forEach((folder) => {
    const files = manifest[folder] || [];
    const meta = folderMeta[folder];
    const bundled = BUNDLED_FILES[folder];
    files.forEach((fileName, idx) => {
      const isNatural = /natural/i.test(fileName);
      const isBundled = bundled.has(fileName);
      const featured = isNatural || idx < 8 || (folder === 'Hats' && fileName === 'Hat 12.wav');
      const encFolder = encodeURIComponent(folder);
      const encFile = encodeURIComponent(fileName);
      entries.push({
        id: `dk1400:${folder}/${fileName}`,
        folder,
        fileName,
        label: formatSampleDisplayLabel(folder, fileName, isNatural || (folder === 'Hats' && fileName === 'Hat 12.wav')),
        category: meta.category,
        subKind: meta.subKind,
        featured,
        hasBundledFallback: isBundled,
        localApiUrl: `/api/drum-kit-1400/${encFolder}/${encFile}`,
        bundledPublicUrl: `/drum-kit-1400/${encFolder}/${encFile}`,
      });
    });
  });

  return entries;
}

export const DRUM_KIT_1400_CATALOG: DrumKit1400SampleEntry[] = buildCatalogFromManifest(RAW_MANIFEST);

const CATALOG_MAP = new Map<string, DrumKit1400SampleEntry>(
  DRUM_KIT_1400_CATALOG.map((e) => [e.id, e])
);

export function getDrumKit1400EntryById(id: string): DrumKit1400SampleEntry | undefined {
  const direct = CATALOG_MAP.get(id);
  if (direct) return direct;
  // Support dynamic newly added files in "1400 Samples Drum Kit" of form "dk1400:<Folder>/<FileName>"
  if (id.startsWith('dk1400:')) {
    const rest = id.slice('dk1400:'.length);
    const slashIdx = rest.indexOf('/');
    if (slashIdx > 0) {
      const folder = rest.slice(0, slashIdx) as DrumKit1400Folder;
      const fileName = rest.slice(slashIdx + 1);
      if (folder === 'Kicks' || folder === 'Snares' || folder === 'Hats' || folder === 'Claps') {
        const encFolder = encodeURIComponent(folder);
        const encFile = encodeURIComponent(fileName);
        const category: CustomSampleCategory =
          folder === 'Kicks' ? 'kick' : folder === 'Hats' ? 'hat' : 'snare';
        const subKind =
          folder === 'Kicks'
            ? 'kick'
            : folder === 'Hats'
            ? 'hat'
            : folder === 'Claps'
            ? 'clap'
            : 'snare';
        return {
          id,
          folder,
          fileName,
          label: formatSampleDisplayLabel(folder, fileName, /natural/i.test(fileName)),
          category,
          subKind,
          featured: /natural/i.test(fileName),
          hasBundledFallback: BUNDLED_FILES[folder]?.has(fileName) ?? false,
          localApiUrl: `/api/drum-kit-1400/${encFolder}/${encFile}`,
          bundledPublicUrl: `/drum-kit-1400/${encFolder}/${encFile}`,
        };
      }
    }
  }
  return undefined;
}

export function getDrumKit1400EntriesByFolder(
  folder: DrumKit1400Folder,
  extraDynamicManifest?: Partial<Record<DrumKit1400Folder, string[]>>
): DrumKit1400SampleEntry[] {
  const base = DRUM_KIT_1400_CATALOG.filter((e) => e.folder === folder);
  const dynFiles = extraDynamicManifest?.[folder];
  if (!dynFiles || dynFiles.length === 0) return base;

  const known = new Set(base.map((b) => b.fileName));
  const extras: DrumKit1400SampleEntry[] = [];
  for (const fn of dynFiles) {
    if (!known.has(fn)) {
      const built = getDrumKit1400EntryById(`dk1400:${folder}/${fn}`);
      if (built) extras.push(built);
    }
  }
  return extras.length > 0 ? [...extras, ...base] : base;
}

/**
 * Returns the primary recommended samples from "1400 Samples Drum Kit" for a given DrumPieceRole.
 * - kick  -> Kicks (500)
 * - snare -> Snares (500) + Claps (50)
 * - hat   -> Hats (350)
 * - tom   -> Featured Kicks & Snares usable as pitched/percussive hits
 * - crash -> Hats & Claps usable as metallic/accent hits
 */
export function getDrumKit1400ForRole(
  role: DrumPieceRole,
  extraDynamicManifest?: Partial<Record<DrumKit1400Folder, string[]>>
): {
  featured: DrumKit1400SampleEntry[];
  primaryFolder: DrumKit1400Folder;
  primaryEntries: DrumKit1400SampleEntry[];
  secondaryFolder?: DrumKit1400Folder;
  secondaryEntries?: DrumKit1400SampleEntry[];
} {
  if (role === 'kick') {
    const kicks = getDrumKit1400EntriesByFolder('Kicks', extraDynamicManifest);
    return {
      featured: kicks.filter((e) => e.featured),
      primaryFolder: 'Kicks',
      primaryEntries: kicks,
    };
  }
  if (role === 'snare') {
    const snares = getDrumKit1400EntriesByFolder('Snares', extraDynamicManifest);
    const claps = getDrumKit1400EntriesByFolder('Claps', extraDynamicManifest);
    return {
      featured: [...snares.filter((e) => e.featured), ...claps.slice(0, 4)],
      primaryFolder: 'Snares',
      primaryEntries: snares,
      secondaryFolder: 'Claps',
      secondaryEntries: claps,
    };
  }
  if (role === 'hat') {
    const hats = getDrumKit1400EntriesByFolder('Hats', extraDynamicManifest);
    return {
      featured: hats.filter((e) => e.featured),
      primaryFolder: 'Hats',
      primaryEntries: hats,
    };
  }
  if (role === 'tom') {
    const kicks = getDrumKit1400EntriesByFolder('Kicks', extraDynamicManifest);
    const snares = getDrumKit1400EntriesByFolder('Snares', extraDynamicManifest);
    return {
      featured: [...kicks.slice(0, 6), ...snares.slice(0, 6)],
      primaryFolder: 'Kicks',
      primaryEntries: kicks.slice(0, 60),
      secondaryFolder: 'Snares',
      secondaryEntries: snares.slice(0, 60),
    };
  }
  // crash
  const hats = getDrumKit1400EntriesByFolder('Hats', extraDynamicManifest);
  const claps = getDrumKit1400EntriesByFolder('Claps', extraDynamicManifest);
  return {
    featured: [...hats.slice(0, 6), ...claps.slice(0, 4)],
    primaryFolder: 'Hats',
    primaryEntries: hats.slice(0, 60),
    secondaryFolder: 'Claps',
    secondaryEntries: claps,
  };
}
